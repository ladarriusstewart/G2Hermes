/**
 * Generate src/generated-endpoint.ts from app.json.
 *
 * `app.json` is the single source of truth for both halves of network access:
 * the `endpoint` the app fetches and the `whitelist` that permits it. Keeping
 * them in one file is the point — they are useless apart, and a mismatch fails
 * silently on the device.
 *
 * So this script also refuses to build a mismatch. If `endpoint` is set and its
 * origin is absent from the whitelist, the Even Realities App blocks the request
 * before it leaves the WebView and the glasses just show "every feed source
 * failed". Failing the build with the exact origin to paste is far kinder.
 *
 * Usage:
 *   node scripts/gen-endpoint.mjs [--manifest app.json] [--out src/generated-endpoint.ts]
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`)
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback
}

const manifestPath = arg('manifest', 'app.json')
const outPath = arg('out', 'src/generated-endpoint.ts')

let manifest
try {
  manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
} catch (err) {
  console.error(`[endpoint] cannot read ${manifestPath}: ${err.message}`)
  process.exit(1)
}

const network = (manifest.permissions ?? []).find((p) => p.name === 'network')
const endpoint = String(network?.endpoint ?? '').trim()
const whitelist = Array.isArray(network?.whitelist) ? network.whitelist : []

if (endpoint) {
  let origin
  try {
    origin = new URL(endpoint).origin
  } catch {
    console.error(`[endpoint] "${endpoint}" in ${manifestPath} is not a valid absolute URL.`)
    console.error('           It must start with https:// (or http:// for local testing).')
    process.exit(1)
  }

  if (!whitelist.includes(origin)) {
    console.error(`[endpoint] ${manifestPath} would fail on the device.\n`)
    console.error(`           endpoint : ${endpoint}`)
    console.error(`           origin   : ${origin}`)
    console.error(`           whitelist: ${whitelist.length ? whitelist.join(', ') : '(empty)'}\n`)
    console.error(`           The whitelist is enforced before the request leaves the WebView and`)
    console.error(`           accepts full origins only — no wildcards. Add this to app.json:\n`)
    console.error(`             "whitelist": [ ${JSON.stringify(origin)} ]\n`)
    process.exit(1)
  }
}

// Only the origin is ever emitted — never the full URL as a secret, and never
// anything from a token. The URL lives in app.json, which is public anyway.
const banner = `// GENERATED by scripts/gen-endpoint.mjs from ${manifestPath} — do not edit.\n`
  + `// Edit \`endpoint\` in ${manifestPath} (keeping its origin in the whitelist) and rebuild.\n`
const body = `export const ENDPOINT = ${JSON.stringify(endpoint)}\n`

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, banner + body)

console.log(endpoint
  ? `[endpoint] ${outPath} <- ${endpoint}`
  : `[endpoint] ${outPath} <- (empty: app renders "Not configured" until set)`)
